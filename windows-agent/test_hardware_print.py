def generate_hardware_test_pdf(target_path: Path) -> Path:
    """Generates a high-quality A4 calibration & verification test sheet."""
    doc = fitz.open()
    page = doc.new_page(width=595, height=842)  # Standard A4 (595x842 pt)

    # 1. Header Box
    rect_header = fitz.Rect(40, 40, 555, 110)
    page.draw_rect(rect_header, color=(0.04, 0.56, 0.91), fill=(0.94, 0.97, 1.0), width=2)
    page.insert_text((60, 75), "PrintX Platform — Hardware Verification Sheet", fontsize=18, color=(0.03, 0.25, 0.53))
    page.insert_text((60, 95), "Smart Self-Service Printing System | Native Windows 11 Controller", fontsize=11, color=(0.3, 0.35, 0.42))

    # 2. Hardware Metadata
    y = 140
    page.insert_text((40, y), "Hardware Profile & Environment:", fontsize=13, color=(0.1, 0.1, 0.1))
    y += 20
    info_lines = [
        "Printer Model: HP Smart Tank 585 Series",
        "Target Queue: HP Smart Tank 580-590 series (USB / Wi-Fi)",
        "Operating System: Windows 11 (pywin32 Spooler Integration)",
        "Rendering Engine: SumatraPDF Headless CLI",
        "Duplex Mode: Simplex (Single-Sided Enforced)",
        f"Verification Timestamp: {time.strftime('%Y-%m-%d %H:%M:%S')}",
    ]
    for line in info_lines:
        page.insert_text((55, y), f"•  {line}", fontsize=10, color=(0.2, 0.2, 0.2))
        y += 18

    # 3. CMYK Color Calibration Blocks
    y += 15
    page.insert_text((40, y), "Color Reproduction Calibration Blocks:", fontsize=13, color=(0.1, 0.1, 0.1))
    y += 15
    colors = [
        ("Cyan", (0.0, 0.7, 0.9)),
        ("Magenta", (0.9, 0.1, 0.5)),
        ("Yellow", (1.0, 0.85, 0.0)),
        ("Key (Black)", (0.05, 0.05, 0.05)),
        ("PrintX Brand", (0.04, 0.56, 0.91)),
    ]
    block_width = 90
    block_height = 40
    start_x = 40
    for idx, (label, color_rgb) in enumerate(colors):
        x = start_x + (idx * 102)
        r = fitz.Rect(x, y, x + block_width, y + block_height)
        page.draw_rect(r, color=(0.2, 0.2, 0.2), fill=color_rgb, width=1)
        # Label below block
        page.insert_text((x + 5, y + block_height + 14), label, fontsize=9, color=(0.2, 0.2, 0.2))

    # 4. Alignment & Margins Grid
    y += 80
    page.insert_text((40, y), "Fine Text & Alignment Check (1200 DPI):", fontsize=13, color=(0.1, 0.1, 0.1))
    y += 18
    sample_text = (
        "The quick brown fox jumps over the lazy dog. 1234567890. "
        "PrintX validates document signatures, page count, and server pricing."
    )
    for fs in [12, 10, 8]:
        page.insert_text((40, y), f"[{fs}pt font] {sample_text}", fontsize=fs, color=(0.1, 0.1, 0.1))
        y += fs + 6

    # 5. Footer & Authenticity Stamp
    rect_footer = fitz.Rect(40, 780, 555, 810)
    page.draw_line(fitz.Point(40, 775), fitz.Point(555, 775), color=(0.8, 0.8, 0.8), width=1)
    page.insert_text((40, 795), "CONFIDENTIAL & OFFICIAL — GENERATED BY PRINTX AUTOMATION HARNESS", fontsize=8, color=(0.5, 0.5, 0.5))
    page.insert_text((430, 795), "A4 SINGLE-SIDED ONLY", fontsize=8, color=(0.04, 0.56, 0.91))

    target_path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(target_path))
    doc.close()
    return target_path


def run_hardware_test(use_virtual: bool = False, copies: int = 1, color_mode: str = "color"):
    setup_agent_logging()
    logger.info("==================================================")
    logger.info(" PrintX — Hardware Printing Verification")
    logger.info("==================================================")

    # 1. Resolve Printer
    target_info = printer_manager.resolve_target_printer()
    if use_virtual:
        for p in printer_manager.get_installed_printers():
            if "PDF" in p.name:
                target_info = p
                break

    if not target_info:
        logger.error("No valid printer queue discovered!")
        return False

    printer_name = target_info.name
    logger.info(f"Target Windows Queue: '{printer_name}' (Driver: {target_info.driver_name})")

    # 2. Generate PDF
    test_pdf = Path("./data/hardware_test_page.pdf").resolve()
    logger.info(f"Generating calibration test page at {test_pdf}...")
    generate_hardware_test_pdf(test_pdf)

    # 3. Create Submission
    job_id = f"TEST-HW-{int(time.time())}"
    submission = PrintJobSubmission(
        job_id=job_id,
        job_number=f"PX-TEST-{int(time.time()) % 10000:04d}",
        pdf_path=str(test_pdf),
        printer_name=printer_name,
        copies=copies,
        color_mode=color_mode,
        page_range="all",
        fit_to_page=True,
        duplex=False,  # Single-sided
        idempotency_key=f"IDEMP-{job_id}"
    )

    # 4. Execute Print Submission
    logger.info(f"Dispatching test job {submission.job_number} via SumatraPDF CLI...")
    success, msg = print_executor.execute_print_job(submission)
    if not success:
        logger.error(f"Print dispatch failed: {msg}")
        return False

    logger.info(f"Submission accepted: {msg}")

    # 5. Monitor Spooler
    logger.info(f"Inspecting Windows Spooler queue for '{printer_name}'...")
    telemetry = spooler_monitor.wait_for_spooler_dispatch(printer_name, timeout_seconds=45)
    logger.info(f"Spooler Telemetry Result: {telemetry}")
    logger.info("==================================================")
    logger.info(f" Verification Complete for queue '{printer_name}'.")
    logger.info("==================================================")
    return True


if __name__ == "__main__":
    use_pdf = "--virtual" in sys.argv
    color = "grayscale" if "--grayscale" in sys.argv else "color"
    run_hardware_test(use_virtual=use_pdf, color_mode=color)

